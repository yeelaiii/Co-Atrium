// Builds assets/pdf-viewer/viewer.html: the source viewer page with pdf.js and its worker
// inlined (base64), so it needs no CDN and works with poor site connectivity.
// Run after changing template.html or upgrading pdfjs-dist:  npm run build:pdf-viewer

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const pdfjs = join(root, 'node_modules', 'pdfjs-dist');
const version = JSON.parse(readFileSync(join(pdfjs, 'package.json'), 'utf8')).version;

// The legacy build carries polyfills (e.g. Uint8Array.prototype.toHex) that older iOS / Android
// WebViews lack; the modern build fails there.
const b64 = (f) => readFileSync(join(pdfjs, 'legacy', 'build', f)).toString('base64');
const html = readFileSync(join(here, 'template.html'), 'utf8')
  .replace('__PDFJS_BASE64__', b64('pdf.min.mjs'))
  .replace('__WORKER_BASE64__', b64('pdf.worker.min.mjs'))
  .replace('<head>', `<head>\n<!-- generated by scripts/pdf-viewer/build.mjs from pdfjs-dist ${version} (legacy build); do not edit -->`);

const out = join(root, 'assets', 'pdf-viewer', 'viewer.html');
writeFileSync(out, html);
console.log(`wrote ${out} (${(html.length / 1024 / 1024).toFixed(2)} MB, pdfjs-dist ${version})`);
