// Builds apps/supabase/seed/deadlines.sql from the versioned seed files:
//   seed/public_holidays_sg.json   Singapore public holidays (MOM)
//   seed/rules/*.json              rule library, one file per standard form + sopa.json + common.json
//
// Every rule file is validated against ruleSchema.ts; the build fails on any error.
// The SQL is idempotent (upserts), so it can be re-run on a hosted database after `db push`:
//   psql "$DATABASE_URL" -f apps/supabase/seed/deadlines.sql
//
// Run from apps/supabase/functions:  deno task build-seed     (add --check to only validate)

import { ruleFileSchema, todoAttributes, TODO } from '../_shared/contracts/ruleSchema.ts';

const root = new URL('../../seed/', import.meta.url);
const checkOnly = Deno.args.includes('--check');

const lit = (v: unknown): string => {
  if (v === null || v === undefined || v === TODO) return 'null';
  if (typeof v === 'number') return String(v);
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  return `'${String(v).replaceAll("'", "''")}'`;
};
const arr = (xs: readonly string[]) => (xs.length ? `array[${xs.map(lit).join(',')}]::text[]` : `'{}'::text[]`);

const errors: string[] = [];
const out: string[] = [
  '-- GENERATED by functions/scripts/build-seed.ts. Do not edit; edit seed/*.json and rebuild.',
  '',
];

// Holidays
const hol = JSON.parse(await Deno.readTextFile(new URL('public_holidays_sg.json', root)));
out.push(`-- Public holidays. Source: ${hol.source_url} (retrieved ${hol.retrieved})`);
for (const h of hol.holidays as { date: string; name: string }[]) {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(h.date)) errors.push(`public_holidays_sg.json: bad date ${h.date}`);
  out.push(
    `insert into public.public_holidays (date, name, source_url) values (${lit(h.date)}, ${lit(h.name)}, ${lit(hol.source_url)})` +
      ` on conflict (date) do update set name = excluded.name, source_url = excluded.source_url;`,
  );
}
out.push('');

// Rules
const keys = new Map<string, string>();
const groups = new Set<string>();
const chains: { file: string; key: string; to: string }[] = [];
const files = [...Deno.readDirSync(new URL('rules/', root))].filter((e) => e.name.endsWith('.json')).map((e) => e.name).sort();
for (const name of files) {
  const raw = JSON.parse(await Deno.readTextFile(new URL(`rules/${name}`, root)));
  const parsed = ruleFileSchema.safeParse(raw);
  if (!parsed.success) {
    for (const i of parsed.error.issues) errors.push(`rules/${name}: ${i.path.join('.')}: ${i.message}`);
    continue;
  }
  out.push(`-- rules/${name} (library ${parsed.data.library_version})`);
  for (const r of parsed.data.rules) {
    const id = `${r.rule_key}@${parsed.data.library_version}`;
    if (keys.has(id)) errors.push(`rules/${name}: duplicate rule_key ${r.rule_key} (also in ${keys.get(id)})`);
    keys.set(id, name);
    groups.add(r.group_key);
    r.chains_to.forEach((to) => chains.push({ file: name, key: r.rule_key, to }));
    if (r.period === null && !r.period_field && r.default_period === null) {
      errors.push(`rules/${name}: ${r.rule_key} has no period, period_field or default_period`);
    }
    const todo = todoAttributes(r);
    out.push(
      `insert into public.rule_library (library_version, rule_key, group_key, kind, obligation, reminder_label,` +
        ` responsible_role, recipient_role, trigger_event_type, period, unit, period_field, default_period,` +
        ` includes_public_holidays, cap_days, cap_label, is_time_bar, consequence, origin, clause_ref, todo_verify,` +
        ` closed_by_event_types, chains_to, applies_to_contract_forms, notes) values (` +
        [
          lit(parsed.data.library_version), lit(r.rule_key), lit(r.group_key), lit(r.kind), lit(r.obligation),
          lit(r.reminder_label), lit(r.responsible_role), lit(r.recipient_role), lit(r.trigger_event_type),
          lit(r.period), lit(r.unit), lit(r.period_field), lit(r.default_period), lit(r.includes_public_holidays),
          lit(r.cap_days), lit(r.cap_label), lit(r.is_time_bar), lit(r.consequence), lit(r.origin), lit(r.clause_ref),
          arr(todo), arr(r.closed_by_event_types), arr(r.chains_to), arr(r.applies_to_contract_forms), lit(r.notes ?? null),
        ].join(', ') +
        `) on conflict (rule_key, library_version) do update set group_key = excluded.group_key, kind = excluded.kind,` +
        ` obligation = excluded.obligation, reminder_label = excluded.reminder_label,` +
        ` responsible_role = excluded.responsible_role, recipient_role = excluded.recipient_role,` +
        ` trigger_event_type = excluded.trigger_event_type, period = excluded.period, unit = excluded.unit,` +
        ` period_field = excluded.period_field, default_period = excluded.default_period,` +
        ` includes_public_holidays = excluded.includes_public_holidays, cap_days = excluded.cap_days,` +
        ` cap_label = excluded.cap_label, is_time_bar = excluded.is_time_bar, consequence = excluded.consequence,` +
        ` origin = excluded.origin, clause_ref = excluded.clause_ref, todo_verify = excluded.todo_verify,` +
        ` closed_by_event_types = excluded.closed_by_event_types, chains_to = excluded.chains_to,` +
        ` applies_to_contract_forms = excluded.applies_to_contract_forms, notes = excluded.notes;`,
    );
  }
  out.push('');
}
for (const c of chains) {
  if (!groups.has(c.to)) errors.push(`rules/${c.file}: ${c.key} chains_to unknown group '${c.to}'`);
}

if (errors.length) {
  console.error(`Seed validation failed:\n  ${errors.join('\n  ')}`);
  Deno.exit(1);
}
if (checkOnly) {
  console.log(`OK: ${keys.size} rules in ${files.length} files, ${hol.holidays.length} holidays.`);
} else {
  await Deno.writeTextFile(new URL('deadlines.sql', root), out.join('\n') + '\n');
  console.log(`Wrote seed/deadlines.sql: ${keys.size} rules, ${hol.holidays.length} holidays.`);
}
